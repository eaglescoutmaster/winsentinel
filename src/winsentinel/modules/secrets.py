"""Leaked secrets: Gitleaks + TruffleHog over code directories, plus plaintext credentials
in dotfiles, persistent environment variables and shell history.

Secret values are never written to the report: tool output is redacted and
TruffleHog's raw matches are discarded in memory. TruffleHog always runs with
--no-verification so found credentials are never sent to a provider.
"""
from __future__ import annotations

import base64
import json
import os
import re
import secrets as pysecrets
import string
import subprocess
import tempfile
from pathlib import Path

from ..config import CODE_SKIP_DIRS, LOCK_FILES
from ..findings import ModuleResult, redact
from ..toolchain import ToolError
from ..winutil import HKCU, HKLM, reg_values

NAME = "secrets"
DESCRIPTION = "Gitleaks + TruffleHog on code dirs (full: git history); plaintext creds in dotfiles, env vars, shell history"
ORDER = 60

_FIXTURE = re.compile(r"(?i)[\\/](tests?|fixtures?|testdata|examples?|samples?|docs?|__tests__|mocks?|fuzz|corpus|benches)[\\/]"
                      r"|\.example$|\.sample$|\.template$|[\\/](readme|changelog)[^\\/]*\.md$")
_CONFIG_NAME = re.compile(r"(?i)(^\.env|config|settings|secret|credential|\.toml$|\.ya?ml$|\.json$|\.ini$)")
_HIGH_VALUE = re.compile(r"(?i)aws|github|gitlab|anthropic|openai|stripe|private[-_ ]?key|slack|azure|gcp|google|npm|pypi|ssh|jwt")
_SECRET_NAME = re.compile(r"(?i)(token|secret|password|passwd|api[_-]?key|private[_-]?key|credential|access[_-]?key)")
_NOT_SECRET_NAME = re.compile(r"(?i)(path|dir|file|url|uri|endpoint|helper|_id$|name$|timeout|enabled|public)")
HISTORY_PATTERNS = [
    ("aws-access-key", re.compile(r"\b(AKIA|ASIA)[0-9A-Z]{16}\b")),
    ("github-token", re.compile(r"\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{36}\b|\bgithub_pat_[A-Za-z0-9_]{60,}\b")),
    ("anthropic-key", re.compile(r"\bsk-ant-[A-Za-z0-9_-]{40,}\b")),
    ("openai-key", re.compile(r"\bsk-(?:proj-)?[A-Za-z0-9_-]{40,}\b")),
    ("slack-token", re.compile(r"\bxox[baprs]-[0-9A-Za-z-]{20,}\b")),
    ("private-key", re.compile(r"-----BEGIN [A-Z ]{0,20}PRIVATE KEY-----")),
    ("password-argument", re.compile(
        r"(?i)(?:password|passwd|pwd|token|secret|api[_-]?key)\s*[=:]\s*[\"']?([^\s\"'$%<>{}]{8,})")),
    ("plaintext-securestring", re.compile(r"(?i)ConvertTo-SecureString\s+[\"']([^\"']{6,})[\"']\s+-AsPlainText")),
    ("credential-in-url", re.compile(r"(?i)\b[a-z][a-z0-9+.-]{1,15}://[^\s/:@]{1,64}:([^\s/@]{6,})@")),
]


def _rand(n: int, alphabet: str = string.ascii_letters + string.digits) -> str:
    return "".join(pysecrets.choice(alphabet) for _ in range(n))


def _gitleaks_config(state_dir: Path) -> Path:
    dirs = "|".join(re.escape(d) for d in sorted(CODE_SKIP_DIRS - {".git"}))
    locks = "|".join(re.escape(f) for f in sorted(LOCK_FILES))
    cfg = state_dir / "gitleaks.toml"
    state_dir.mkdir(parents=True, exist_ok=True)
    cfg.write_text(
        "# generated by winsentinel\n[extend]\nuseDefault = true\n\n[[allowlists]]\n"
        'description = "dependency/build directories and lock files"\n'
        f"paths = ['''(?i)(^|[\\\\/])({dirs})[\\\\/]''', '''(?i)(^|[\\\\/])({locks})$''']\n",
        "utf-8",
    )
    return cfg


def _trufflehog_excludes(state_dir: Path) -> Path:
    p = state_dir / "trufflehog-exclude.txt"
    lines = [f"(^|[\\\\/]){re.escape(d)}[\\\\/]" for d in sorted(CODE_SKIP_DIRS)]
    lines += [f"{re.escape(f)}$" for f in sorted(LOCK_FILES)]
    p.write_text("\n".join(lines) + "\n", "utf-8")
    return p


def run_gitleaks(ctx, target: Path, history: bool, cfg: Path) -> list[dict]:
    with tempfile.TemporaryDirectory(prefix="ws-gl-") as td:
        out = Path(td) / "gitleaks.json"
        args = ["git" if history else "dir", str(target), "--config", str(cfg), "--report-format", "json",
                "--report-path", str(out), "--redact", "--no-banner", "--no-color", "--exit-code", "0",
                "--max-target-megabytes", "5", "--log-level", "error"]
        if history:
            args.append("--log-opts=--all")
        p = ctx.tools.run("gitleaks", args, timeout=1800)
        if not out.exists():
            raise ToolError(f"gitleaks produced no report (exit {p.returncode}): {p.stderr.decode('utf-8', 'replace')[:300]}")
        data = json.loads(out.read_text("utf-8") or "[]")
    return [{"tool": "gitleaks", "rule": d.get("RuleID", "?"), "file": d.get("File", ""), "line": d.get("StartLine", 0),
             "commit": d.get("Commit", ""), "desc": d.get("Description", "")} for d in data or []]


def run_trufflehog(ctx, target: Path, history: bool, excl: Path) -> list[dict]:
    if history:
        args = ["git", "file:///" + str(target).replace("\\", "/"), "--no-verification", "--json", "--no-update"]
    else:
        args = ["filesystem", str(target), "--no-verification", "--json", "--no-update", "--exclude-paths", str(excl)]
    p = ctx.tools.run("trufflehog", args, timeout=1800)
    rows = []
    for line in p.stdout.decode("utf-8", "replace").splitlines():
        if not line.startswith("{"):
            continue
        try:
            d = json.loads(line)
        except ValueError:
            continue
        if "DetectorName" not in d:
            continue
        meta = (d.get("SourceMetadata") or {}).get("Data") or {}
        src = meta.get("Filesystem") or meta.get("Git") or {}
        f = src.get("file", "")
        if history and f and not os.path.isabs(f):
            f = str(target / f)
        # d["Raw"] holds the secret: deliberately not copied.
        rows.append({"tool": "trufflehog", "rule": d.get("DetectorName", "?"), "file": f, "line": src.get("line", 0),
                     "commit": src.get("commit", ""), "desc": d.get("DetectorDescription", "")})
    if p.returncode not in (0, 183) and not rows:
        raise ToolError(f"trufflehog exit {p.returncode}: {p.stderr.decode('utf-8', 'replace')[-300:]}")
    return rows


def preflight(ctx, res: ModuleResult, cfg: Path, excl: Path) -> dict[str, bool]:
    """Plant fabricated secrets in a temp dir and confirm each tool reports them.
    A scanner that finds nothing in the canary would otherwise look like a clean result."""
    ok = {}
    with tempfile.TemporaryDirectory(prefix="ws-canary-") as td:
        d = Path(td)
        key_id = "AKIA" + _rand(16, "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567")
        (d / "settings.py").write_text(
            f'aws_access_key_id = "{key_id}"\naws_secret_access_key = "{_rand(40)}"\n'
            f'github_token = "ghp_{_rand(36)}"\n', "utf-8")
        for name, fn, extra in (("gitleaks", run_gitleaks, cfg), ("trufflehog", run_trufflehog, excl)):
            if not ctx.tools.path(name):
                res.note(f"{name} not installed (winsentinel tools install): skipped")
                ok[name] = False
                continue
            try:
                found = fn(ctx, d, False, extra)
                ok[name] = len(found) > 0
                if not found:
                    res.note(f"{name} BROKEN: ran but missed the planted canary secret; its results are not trusted")
            except (ToolError, OSError, ValueError) as e:
                ok[name] = False
                res.note(f"{name} BROKEN: {e}")
    res.coverage["tool_preflight"] = ", ".join(f"{k}={'OK' if v else 'UNAVAILABLE'}" for k, v in ok.items())
    return ok


def _git_tracked(repo: Path, file: str) -> bool:
    try:
        p = subprocess.run(["git", "-C", str(repo), "ls-files", "--error-unmatch", file], capture_output=True,
                           timeout=20, stdin=subprocess.DEVNULL)
        return p.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def _scan_code(ctx, res: ModuleResult, ok: dict[str, bool], cfg: Path, excl: Path) -> None:
    targets = ctx.paths or [d for d in ctx.cfg.code_dirs if d.is_dir()]
    missing = [str(d) for d in ctx.cfg.code_dirs if not d.is_dir()] if not ctx.paths else []
    if missing:
        res.note(f"code directories not found: {', '.join(missing)}")
    scanned = 0
    for target in targets:
        rows: list[dict] = []
        is_repo = (target / ".git").exists()
        modes = [False] + ([True] if ctx.full and is_repo else [])
        for history in modes:
            if ok.get("gitleaks"):
                try:
                    rows += [dict(r, history=history) for r in run_gitleaks(ctx, target, history, cfg)]
                except (ToolError, OSError, ValueError) as e:
                    res.note(f"gitleaks failed on {target.name}: {e}")
            if ok.get("trufflehog"):
                try:
                    rows += [dict(r, history=history) for r in run_trufflehog(ctx, target, history, excl)]
                except (ToolError, OSError, ValueError) as e:
                    res.note(f"trufflehog failed on {target.name}: {e}")
        scanned += 1
        by_file: dict[str, dict] = {}
        for r in rows:
            f = r["file"]
            if f and not os.path.isabs(f):
                f = str(target / f)
            f = os.path.normpath(f)
            parts = {p.lower() for p in Path(f).parts}
            if parts & (CODE_SKIP_DIRS - {".git"}) or Path(f).name.lower() in LOCK_FILES:
                continue
            m = by_file.setdefault(os.path.normcase(f), {"file": f, "lines": set(), "tools": {}, "commit": "", "history_only": True})
            m["lines"].add(int(r["line"] or 0))
            m["tools"].setdefault(r["tool"], set()).add(r["rule"])
            m["commit"] = m["commit"] or r["commit"]
            if not r["history"]:
                m["history_only"] = False
        for m in by_file.values():
            rules = sorted({x for v in m["tools"].values() for x in v})
            kinds = ", ".join(rules)
            lines = sorted(m["lines"])
            signals = [f"{t}: {', '.join(sorted(v))}" for t, v in sorted(m["tools"].items())]
            exists = os.path.isfile(m["file"])
            rel = os.path.relpath(m["file"], target) if exists else m["file"]
            tracked = is_repo and exists and _git_tracked(target, rel)
            generic_only = all(r.lower() in ("generic-api-key", "jwt", "curl-auth-header") for r in rules)
            sev = "medium"
            if generic_only and not _CONFIG_NAME.search(Path(m["file"]).name):
                sev = "low"
            elif len(m["tools"]) >= 2 or _HIGH_VALUE.search(kinds):
                sev = "high" if (tracked or (m["history_only"] and m["commit"])) else "medium"
            if tracked:
                signals.append("file is tracked by git (secret is in the repository)")
            if m["history_only"]:
                signals.append(f"present in git history (commit {m['commit'][:10]}) though not in the working tree")
            if _FIXTURE.search(m["file"]):
                sev = "low"
                signals.append("path looks like test/example/fuzz/documentation content")
            shown = ", ".join(str(n) for n in lines[:8]) + (f" (+{len(lines) - 8} more)" if len(lines) > 8 else "")
            res.add(rule_id="SECRET-CODE", title=f"Possible secret ({kinds[:60]}) in {Path(m['file']).name}", severity=sev,
                    evidence=f"{m['file']}:{lines[0]}", why="; ".join(signals) + f". Lines: {shown}. Values withheld from this report.",
                    confidence=0.7 if len(m["tools"]) >= 2 else 0.5, signals=signals,
                    remediation="If real: rotate/revoke the credential first, then remove it from the file. A secret "
                                "that reached git history stays valid until rotated, even after deletion.",
                    details={"line": lines[0], "lines": lines[:50], "key": kinds, "commit": m["commit"],
                             "source_file": m["file"], "value": f"{kinds}|{len(lines)}"})
    res.coverage["code_dirs_scanned"] = scanned
    res.coverage["git_history"] = "yes" if ctx.full else "no (quick mode: working tree only)"


def _fact(res, rule, title, sev, evidence, why, fix, key, value=""):
    res.add(rule_id=rule, title=title, severity=sev, evidence=evidence, why=why, confidence=0.8, kind="fact",
            remediation=fix, details={"key": key, "value": value})


def _openssh_unencrypted(data: bytes) -> bool | None:
    m = re.search(rb"-----BEGIN OPENSSH PRIVATE KEY-----(.+?)-----END", data, re.S)
    if m:
        try:
            raw = base64.b64decode(b"".join(m.group(1).split()))
        except ValueError:
            return None
        if raw.startswith(b"openssh-key-v1\x00"):
            n = int.from_bytes(raw[15:19], "big")
            return raw[19 : 19 + n] == b"none"
        return None
    if b"PRIVATE KEY-----" in data:
        return b"ENCRYPTED" not in data
    return None


def _dotfiles(res: ModuleResult) -> None:
    home = Path.home()
    rotate = "Use a credential manager/helper instead of a plaintext file, and rotate the credential if the file was ever copied or backed up."

    def text(p: Path) -> str:
        try:
            return p.read_text("utf-8", "replace") if p.is_file() and p.stat().st_size < 2_000_000 else ""
        except OSError:
            return ""

    for m in re.finditer(r"(?m)^\s*(\S*:?_(?:authToken|auth|password))\s*=\s*(\S+)", text(home / ".npmrc")):
        if not m.group(2).startswith("${"):
            _fact(res, "SECRET-NPMRC", "npm auth token in .npmrc", "medium", str(home / ".npmrc"),
                  f"{m.group(1)} = {redact(m.group(2))}", rotate, m.group(1), redact(m.group(2)))
    for name in (".netrc", "_netrc"):
        if re.search(r"(?i)\bpassword\s+\S+", text(home / name)):
            _fact(res, "SECRET-NETRC", f"Password in {name}", "medium", str(home / name),
                  "File holds machine/login/password entries in clear text.", rotate, name)
    if re.search(r"://[^:/\s]+:[^@\s]+@", text(home / ".git-credentials")):
        _fact(res, "SECRET-GIT-CRED", "Git credentials stored in plaintext", "medium", str(home / ".git-credentials"),
              "credential.helper=store keeps tokens unencrypted.", "git config --global credential.helper manager, then delete the file and rotate the token.", "git")
    aws = text(home / ".aws" / "credentials")
    if re.search(r"(?im)^\s*aws_secret_access_key\s*=\s*\S+", aws):
        long_lived = bool(re.search(r"(?m)=\s*AKIA", aws))
        _fact(res, "SECRET-AWS", "AWS access keys in ~/.aws/credentials", "medium" if long_lived else "low",
              str(home / ".aws" / "credentials"), ("Long-lived (AKIA) keys" if long_lived else "Temporary keys") + " stored in clear text.",
              "Prefer aws sso login / short-lived credentials; rotate long-lived keys regularly.", "aws")
    try:
        dc = json.loads(text(home / ".docker" / "config.json") or "{}")
        inline = [h for h, v in (dc.get("auths") or {}).items() if isinstance(v, dict) and v.get("auth")]
        if inline:
            _fact(res, "SECRET-DOCKER", "Docker registry credentials stored inline", "medium", str(home / ".docker" / "config.json"),
                  f"Base64 (not encrypted) credentials for: {', '.join(inline)}.", "Configure a credsStore (wincred) and run docker logout/login.", "docker", ",".join(inline))
    except ValueError:
        pass
    if re.search(r"(?im)^\s*password\s*[=:]\s*\S+", text(home / ".pypirc")):
        _fact(res, "SECRET-PYPIRC", "PyPI password/token in .pypirc", "medium", str(home / ".pypirc"),
              "Upload credential stored in clear text.", rotate, "pypirc")
    ssh = home / ".ssh"
    if ssh.is_dir():
        for p in ssh.iterdir():
            if p.is_file() and p.suffix != ".pub" and p.stat().st_size < 20_000:
                try:
                    if _openssh_unencrypted(p.read_bytes()):
                        _fact(res, "SECRET-SSH-NOPASS", f"SSH private key without passphrase: {p.name}", "low", str(p),
                              "Anything that can read this file can use the key.", "ssh-keygen -p -f <key> to add a passphrase; use ssh-agent.", p.name)
                except OSError:
                    pass


def _environment(res: ModuleResult) -> None:
    sources = [(HKCU, "Environment", "HKCU\\Environment"),
               (HKLM, r"SYSTEM\CurrentControlSet\Control\Session Manager\Environment", "HKLM system environment")]
    for root, key, label in sources:
        for name, val in reg_values(root, key).items():
            if not isinstance(val, str) or len(val) < 12 or "%" in val or "\\" in val or "/" in val[:3]:
                continue
            if _SECRET_NAME.search(name) and not _NOT_SECRET_NAME.search(name):
                _fact(res, "SECRET-ENV", f"Secret in persistent environment variable {name}", "medium", f"{label} :: {name}",
                      f"Value {redact(val)} is handed to every process you start and is readable from the registry.",
                      "Remove it (System Properties > Environment Variables) and load it per-session or from a secret store.",
                      name, redact(val))


def _history(res: ModuleResult) -> None:
    files = [Path(os.environ.get("APPDATA", "")) / "Microsoft/Windows/PowerShell/PSReadLine/ConsoleHost_history.txt",
             Path.home() / ".bash_history", Path.home() / ".zsh_history", Path.home() / ".python_history"]
    for f in files:
        try:
            if not f.is_file():
                continue
            lines = f.read_text("utf-8", "replace").splitlines()
        except OSError:
            continue
        res.coverage["history_files"] = res.coverage.get("history_files", 0) + 1
        seen: set[tuple] = set()
        for i, line in enumerate(lines, 1):
            for kind, pat in HISTORY_PATTERNS:
                m = pat.search(line)
                if not m:
                    continue
                secret = m.group(m.lastindex or 0)
                if kind in ("password-argument", "credential-in-url") and (len(set(secret)) < 5 or secret.lower() in ("password", "changeme", "$password")):
                    continue
                key = (kind, secret)
                if key in seen:
                    break
                seen.add(key)
                res.add(rule_id="SECRET-HISTORY", title=f"Credential typed into shell history ({kind})",
                        severity="medium" if kind not in ("password-argument",) else "low", evidence=f"{f}:{i}",
                        why=f"History line {i} contains a {kind} value {redact(secret)}. History files are plain text and "
                            "are a first stop for info-stealers.", confidence=0.5,
                        signals=[f"history pattern {kind}"],
                        remediation="Rotate the credential, then delete that line from the history file.",
                        details={"line": i, "key": f"{kind}|{redact(secret)}", "source_file": str(f), "value": redact(secret)})
                break


def run(ctx) -> ModuleResult:
    res = ModuleResult(NAME)
    cfg = _gitleaks_config(ctx.cfg.state_dir)
    excl = _trufflehog_excludes(ctx.cfg.state_dir)
    ok = preflight(ctx, res, cfg, excl)
    if any(ok.values()):
        _scan_code(ctx, res, ok, cfg, excl)
    else:
        res.note("no working secret scanner: code directories were NOT scanned for secrets")
    if not ctx.paths:
        _dotfiles(res)
        _environment(res)
        _history(res)
    return res
